# encryption.py
"""Encryption utilities for SecureCloud.
Provides functions to generate a per‑file AES‑256‑GCM key, encrypt a block,
and decrypt a block. Uses the `cryptography` library.
"""

import os
from typing import Tuple
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# 256‑bit (32‑byte) key size for AES‑GCM
KEY_SIZE = 32
# 96‑bit (12‑byte) nonce size – recommended for AES‑GCM
NONCE_SIZE = 12


def generate_key() -> bytes:
    """Generate a fresh random 256‑bit AES‑GCM key.

    Returns
    -------
    bytes
        Randomly generated key suitable for `AESGCM`.
    """
    return os.urandom(KEY_SIZE)


def encrypt_block(plaintext: bytes, key: bytes) -> Tuple[bytes, bytes]:
    """Encrypt a single block with AES‑256‑GCM.

    Parameters
    ----------
    plaintext: bytes
        The block data to encrypt.
    key: bytes
        The 256‑bit AES key (must be exactly 32 bytes).

    Returns
    -------
    Tuple[bytes, bytes]
        ``(nonce, ciphertext)`` where ``ciphertext`` already includes the
        authentication tag generated by ``AESGCM``.
    """
    if len(key) != KEY_SIZE:
        raise ValueError("AES‑GCM key must be 32 bytes long")
    nonce = os.urandom(NONCE_SIZE)
    aesgcm = AESGCM(key)
    ciphertext = aesgcm.encrypt(nonce, plaintext, associated_data=None)
    return nonce, ciphertext


def decrypt_block(nonce: bytes, ciphertext: bytes, key: bytes) -> bytes:
    """Decrypt a block encrypted with :func:`encrypt_block`.

    Parameters
    ----------
    nonce: bytes
        The 12‑byte nonce used during encryption.
    ciphertext: bytes
        The ciphertext **including** the authentication tag.
    key: bytes
        The original 256‑bit AES‑GCM key.

    Returns
    -------
    bytes
        The original plaintext block.
    """
    if len(key) != KEY_SIZE:
        raise ValueError("AES‑GCM key must be 32 bytes long")
    aesgcm = AESGCM(key)
    # ``decrypt`` will raise an exception if authentication fails.
    return aesgcm.decrypt(nonce, ciphertext, associated_data=None)
